print(df.shape)  # (24, 6)

# 1. p-value가 가장 작은 독립변수의 회귀계수 값 출력
import statsmodels.formula.api as smf

model = smf.ols('성적 ~ 공부시간 + 과제점수 + 모의고사 + 출석률 + 수면시간', data=df).fit()
print(model.summary()) # 모의고사 p-value가 0이다.
print(np.round(0.9168, 3)) # 0.917

# 0.05보다 큰 p value를 삭제 :  과제점수, 수면시간 삭제
model = smf.ols('성적 ~ 공부시간 + 모의고사 + 출석률', data=df.drop(['과제점수', '수면시간'], axis = 1)).fit()
print(model.summary())
print(round(0.995, 3))

df = pd.DataFrame({'공부시간' :[9], '모의고사':[82], '출석률' : [95]})

result = model.predict(df)
print(round(result[0], 3))