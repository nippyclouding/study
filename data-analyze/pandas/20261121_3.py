def problem_3() : 
    print("일한 30명의 실험 참가자를 대상으로 기존 약 A와 신약 B의 효능 지속시간(분)을 각각 측정하였다."
    "- A 컬럼: 참가자가 A약을 복용한 후 측정한 효능 지속시간"
    "- B 컬럼: 동일한 참가자가 B약을 복용한 후 측정한 효능 지속시간" \
    "두 컬럼의 같은 행은 동일한 실험 참가자의 측정 결과를 의미한다." \
    "문제: A약과 B약의 효능 지속시간에 통계적으로 유의미한 차이가 있는지 유의수준 0.05에서 검정하시오." \
    "검정 조건"
    "- 두 약의 효능 지속시간 차이값은 정규성을 만족하지 않는다고 가정한다."
    "- 두 측정값은 서로 대응되는 표본이다."
    "- Wilcoxon 부호순위 검정을 사용한다.")


df = pd.DataFrame({
    "A": [81.5, 79.6, 81.9, 84.6, 79.3, 79.3, 84.7, 82.3, 78.6, 81.6,
          78.6, 78.6, 80.7, 74.3, 74.8, 78.3, 77.0, 80.9, 77.3, 75.8,
          84.4, 79.3, 80.2, 75.7, 78.4, 80.3, 76.5, 81.1, 78.2, 79.1],
    "B": [81.2, 86.6, 83.4, 82.9, 83.3, 77.1, 86.9, 77.9, 76.1, 83.7,
          82.3, 80.6, 81.9, 74.9, 71.9, 77.7, 77.1, 85.6, 79.8, 72.0,
          86.9, 79.7, 79.7, 79.1, 83.0, 84.6, 75.5, 81.7, 80.7, 83.6]
})

# A 컬럼: A약을 복용한 후 측정한 효능 지속시간
# B 컬럼: B약을 복용한 후 측정한 효능 지속시간


from scipy import stats

a = 0.05


# 1. 귀무가설 : A약과 B약의 평균 효능 지속시간은 같다.
# p_value = stats.ttest_ind(df['A'], df['B'])[1] 이것을 실행하기 전 등분산 가정을 먼저 해야 한다.

problem_1()

# 귀무가설 : a, b는 분산이 동일하다.
p_value = stats.levene(df['A'], df['B'])[1]
if p_value < a : 
    p_value = stats.ttest_ind(df['A'], df['B'], equal_var = False)[1]
else : # 독립 표본 t검정
    p_value = stats.ttest_ind(df['A'], df['B'])[1]

print(round(p_value, 3))




problem_2()
# 귀무가설(H0): A약과 B약의 평균 효능 지속시간은 같다.
# 대립가설(H1): A약과 B약의 평균 효능 지속시간은 다르다.

p_value = stats.ttest_rel(df['A'], df['B'])[1]
print(round(p_value, 3))


problem_3()

# 귀무가설 : A약과 B약의 효능 지속시간에 통계적으로 유의미한 차이가 없다. (평균 동일)
# 대립가설 : 평균에 차이가 있다.

# 윌콕슨 비모수 검정
p_value = stats.wilcoxon(df['A'], df['B'])[1]
print(round(p_value, 3))